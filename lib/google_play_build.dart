// ============================================================
//  Сборка для Google Play: что прячем на время проверки (20.09.2026)
// ============================================================
//
// Google смотрит на приложение глазами проверяющего, и всё лишнее на экране
// это лишний повод для отказа. Поэтому на время сборки прячем разделы, до
// которых площадка ещё не дошла: товарную часть, бронирование и баланс.
//
// ВАЖНО: ничего не удалено и не закомментировано. Здесь один выключатель, и
// возврат к обычному приложению это ОДНА строка ниже: `false` вместо `true`.
// Сознательно не делаем из этого флаг сборки (`--dart-define`): собирать
// будут руками, и забытый ключ означал бы «собрали не то».
//
// Что прячется, когда выключатель включён:
//
//   каталоги       — в списке остаются только разрешённые ниже, и это видно
//                    и на главной, и в «Смотреть все», и при создании
//                    объявления: все три экрана читают один и тот же ответ;
//   профиль        — пункты «Брони», «Заказы»,
//                    «Покупки» и карточка «ФИНАНСЫ»;
//   нижнее меню    — иконка корзины.
//
// Сам сервер при этом не трогаем: он как отдавал всё, так и отдаёт. Это
// решение приложения и только его.

/// Выключатель сборки для Google Play.
///
/// `true`  — прячем то, что перечислено выше;
/// `false` — обычное приложение, как на деве и в RuStore.
const bool kGooglePlayBuild = false;

/// Каталоги, которые видно в сборке для Google Play.
///
/// Сравниваем по НАЧАЛУ названия, а не по вхождению: «Медицинские услуги»
/// не должны проехать по слову «услуг», а «Работа и вакансии ВСЕХ сфере
/// специальностях» обязана остаться. Регистр не важен, «ё» и «е» считаем
/// одной буквой.
///
/// Чтобы добавить или убрать раздел, правится только этот список.
const List<String> kGooglePlayCatalogPrefixes = [
  'недвиж',
  'работ', // сюда же попадает «Подработка»
  'подработ',
  'бизнес',
  'услуг',
  'оборудован',
  'аренд',
  'прокат',
];

/// То же самое для слага: названия на сервере могут поменять, слаг меняют
/// гораздо реже.
const List<String> kGooglePlayCatalogSlugPrefixes = [
  'nedvizh',
  'rabot',
  'podrabot',
  'biznes',
  'uslug',
  'oborudovan',
  'arend',
  'prokat',
  'real-estate',
  'rent',
  'job',
  'work',
];

/// Видно ли этот каталог в сборке для Google Play.
///
/// Вне сборки отвечает `true` всегда: в обычном приложении каталоги не
/// фильтруются вовсе.
bool isCatalogVisibleInBuild(String? name, {String? slug}) {
  if (!kGooglePlayBuild) return true;

  final title = _normalize(name);
  final key = _normalize(slug);

  if (title.isEmpty && key.isEmpty) {
    // Каталог без названия показывать всё равно нечем, и пропускать его
    // «на всякий случай» значит пустить в список неизвестно что.
    return false;
  }

  for (final prefix in kGooglePlayCatalogPrefixes) {
    if (title.startsWith(prefix)) return true;
  }

  for (final prefix in kGooglePlayCatalogSlugPrefixes) {
    if (key.startsWith(prefix)) return true;
  }

  return false;
}

/// Оставить в списке только разрешённые каталоги.
///
/// Принимает любой список: у каталогов объявлений и у карточек главного
/// экрана разные классы, а правило одно.
List<T> keepCatalogsForBuild<T>(
  List<T> items, {
  required String? Function(T item) name,
  String? Function(T item)? slug,
}) {
  if (!kGooglePlayBuild) return items;

  return items
      .where((item) => isCatalogVisibleInBuild(
            name(item),
            slug: slug?.call(item),
          ))
      .toList();
}

String _normalize(String? value) {
  if (value == null) return '';

  return value.trim().toLowerCase().replaceAll('ё', 'е');
}
