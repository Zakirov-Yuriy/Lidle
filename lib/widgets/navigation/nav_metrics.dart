// ============================================================
// "Размеры нижнего меню"
// ============================================================
//
// С появлением пункта «Мой магазин» в панели стало семь значков вместо шести
// (17.09.2026). При прежних отступах ряд не помещается по ширине на обычном
// телефоне, а на узком не помещался бы и с уменьшенными «на глаз». Поэтому
// отступ считается от ширины экрана: значки всегда влезают, а на широком
// остаются такими же просторными, как раньше.

import 'package:flutter/material.dart';

/// Горизонтальный отступ вокруг значка нижнего меню.
double navItemGap(BuildContext context, {required bool showStore}) {
  if (!showStore) return 13.5;

  const double icon = 28; // ширина самого значка
  const double outer = 24; // поля панели слева и справа
  const int items = 7;

  final width = MediaQuery.of(context).size.width - outer;
  final gap = (width / items - icon) / 2;

  // Нижняя граница — чтобы значки не слиплись, верхняя — прежний отступ.
  return gap.clamp(4.0, 13.5);
}
