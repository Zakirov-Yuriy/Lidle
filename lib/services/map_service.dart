import 'package:flutter_dotenv/flutter_dotenv.dart';
import 'package:lidle/core/logger.dart';
import 'package:yandex_maps_mapkit_lite/init.dart' as mapkit_init;
import 'package:yandex_maps_mapkit_lite/mapkit_factory.dart';

/// Карты Яндекса: включение и жизненный цикл (задача 71, 26.11.2026).
///
/// ЗАЧЕМ ОТДЕЛЬНАЯ СЛУЖБА. Карта требует двух вещей, которые легко забыть и
/// трудно потом найти: ключ надо отдать один раз при запуске приложения, а
/// саму карту надо будить и усыплять, когда она появляется и пропадает с
/// глаз. Без второго карта остаётся серым прямоугольником, и понять, почему,
/// по коду экрана невозможно.
///
/// ПОЧЕМУ СЧЁТЧИК, А НЕ ПРОСТО ВКЛЮЧИТЬ И ВЫКЛЮЧИТЬ. Карт на экране может
/// оказаться две: карточка объявления с маленькой картой, а поверх неё
/// открытая во весь экран. Когда человек закрывает верхнюю, нижняя остаётся
/// видимой, и выключать карты в этот миг нельзя.
///
/// БЕЗ КЛЮЧА НИЧЕГО НЕ ПАДАЕТ. Если ключа в настройках нет, служба просто
/// остаётся выключенной, а экраны вместо карты показывают адрес строкой.
/// Приложение должно работать и у того, кто собрал его без ключа.
class MapService {
  MapService._();

  static bool _ready = false;

  /// Карты готовы к показу. Если нет, блоки с картой не рисуются.
  static bool get ready => _ready;

  /// Сколько карт сейчас на экране.
  static int _visible = 0;

  /// Вызывается один раз при запуске приложения, после чтения настроек.
  static Future<void> init() async {
    final key = (dotenv.env['YANDEX_MAPKIT_KEY'] ?? '').trim();

    if (key.isEmpty) {
      log.w('Карты: ключ YANDEX_MAPKIT_KEY не задан, карта показываться не будет');

      return;
    }

    try {
      await mapkit_init.initMapkit(apiKey: key);
      _ready = true;
    } catch (e) {
      // Неверный ключ, нет сети при первом запуске, что угодно. Приложение
      // от этого работать не перестаёт.
      log.e('Карты: не удалось включить MapKit: $e');
      _ready = false;
    }
  }

  /// Карта появилась на экране.
  static void mapShown() {
    if (!_ready) return;

    _visible++;

    if (_visible == 1) {
      mapkit.onStart();
    }
  }

  /// Карта ушла с экрана.
  static void mapHidden() {
    if (!_ready) return;

    _visible--;

    if (_visible <= 0) {
      _visible = 0;
      mapkit.onStop();
    }
  }
}
