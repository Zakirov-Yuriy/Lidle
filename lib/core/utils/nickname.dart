/// Короткое имя пользователя: как его показывать (12.10.2026, задача 62).
///
/// В базе имя хранится БЕЗ собачки и БЕЗ пробелов: пробел при вводе
/// превращается в подчёркивание, потому что имя работает как адрес. Но
/// подчёркивание на экране выглядит как логин со старого форума, поэтому при
/// показе мы возвращаем ему человеческий вид.
///
///     в базе      ООО_Авангард
///     на экране   @ООО Авангард
///
/// ВАЖНО: в поле ввода подставлять ЭТО нельзя, только настоящее значение.
/// Иначе человек, ничего не трогая, сохранит себе имя с пробелом, а сервер
/// снова превратит его в подчёркивание, и так по кругу.
library;

/// Короткое имя для показа.
///
/// [nickname] это значение из базы, [fallbackName] обычное имя, которым мы
/// подменяем короткое, если его не завели.
String nicknameForDisplay(String? nickname, {String? fallbackName}) {
  final value = (nickname ?? '').trim();

  if (value.isEmpty) {
    return '@${(fallbackName ?? '').trim()}';
  }

  return '@${prettyNickname(value)}';
}

/// Короткое имя без собачки, подчёркивания заменены пробелами.
String prettyNickname(String nickname) {
  final value = nickname.trim();

  return (value.startsWith('@') ? value.substring(1) : value)
      .replaceAll('_', ' ');
}
