import 'dart:async';

/// Связь между уведомлением и открытой перепиской (12.10.2026).
///
/// ЗАЧЕМ. Экран переписки перечитывал сообщения по таймеру. Человек стоял в
/// чате, собеседник писал, приходило уведомление, а сама переписка пустовала
/// до следующего срабатывания таймера. Выглядело так, будто чат сломан:
/// уведомление есть, сообщения нет.
///
/// Теперь уведомление, пришедшее при открытом приложении, сразу сообщает
/// сюда номер чата. Открытый экран это слышит и перечитывает ленту, не
/// дожидаясь таймера.
///
/// ВТОРОЕ НАЗНАЧЕНИЕ. Здесь же лежит номер переписки, открытой прямо сейчас.
/// По нему уведомление о сообщении из ЭТОГО чата не показывается вовсе:
/// человек и так на него смотрит, а всплывающая подсказка поверх
/// собственного разговора только мешает. Так ведут себя все мессенджеры.
class ChatEvents {
  ChatEvents._();

  static final ChatEvents instance = ChatEvents._();

  final _incoming = StreamController<int>.broadcast();

  /// Номера чатов, в которые только что пришло сообщение.
  Stream<int> get onIncoming => _incoming.stream;

  /// Переписка, открытая сейчас. Пусто, если человек не в чате.
  int? openChatId;

  /// Собеседник в открытой переписке.
  ///
  /// Нужен отклику и предложению цены: у них в уведомлении нет номера чата,
  /// зато есть номер того, кто откликнулся или предложил. Если человек
  /// прямо сейчас разговаривает с ним, уведомление не нужно: и отклик, и
  /// предложение заводят сообщение, и оно появится в ленте на глазах.
  int? openPeerId;

  /// Пришло сообщение в этот чат.
  void notifyIncoming(int chatId) {
    if (chatId <= 0) {
      return;
    }

    _incoming.add(chatId);
  }

  /// Смотрит ли человек прямо сейчас на эту переписку.
  bool isOpen(int chatId) => openChatId != null && openChatId == chatId;

  /// Разговаривает ли человек прямо сейчас с этим собеседником.
  bool isTalkingTo(int? userId) =>
      userId != null && openPeerId != null && openPeerId == userId;
}
